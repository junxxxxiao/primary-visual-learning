const ALLOWED_NODE_KINDS = new Set(["point", "box", "anchor"]);
const ALLOWED_ANCHORS = new Set(["center", "top", "right", "bottom", "left"]);

function assertFinite(value, label) {
  if (!Number.isFinite(value)) throw new Error(`${label} must be finite`);
}

function validateNode(node) {
  if (!node || typeof node.id !== "string" || !/^[a-z0-9][a-z0-9._-]{0,95}$/.test(node.id)) {
    throw new Error("node id is invalid");
  }
  if (!ALLOWED_NODE_KINDS.has(node.kind)) throw new Error(`node kind is not allowed: ${node.kind}`);
  for (const key of ["x", "y", "width", "height"]) assertFinite(node[key], `node.${node.id}.${key}`);
  if (node.width <= 0 || node.height <= 0) throw new Error(`node ${node.id} has non-positive size`);
}

function resolveAnchor(node, anchor) {
  if (!ALLOWED_ANCHORS.has(anchor)) throw new Error(`anchor is not allowed: ${anchor}`);
  const halfW = node.width / 2;
  const halfH = node.height / 2;
  if (anchor === "top") return { x: node.x, y: node.y - halfH };
  if (anchor === "right") return { x: node.x + halfW, y: node.y };
  if (anchor === "bottom") return { x: node.x, y: node.y + halfH };
  if (anchor === "left") return { x: node.x - halfW, y: node.y };
  return { x: node.x, y: node.y };
}

function resolveConnector(connector, nodes) {
  if (!connector || typeof connector.id !== "string") throw new Error("connector id is required");
  const fromNode = nodes.get(connector.from?.node_id);
  const toNode = nodes.get(connector.to?.node_id);
  if (!fromNode || !toNode) throw new Error(`connector ${connector.id} references an unknown node`);
  return {
    id: connector.id,
    from: resolveAnchor(fromNode, connector.from.anchor),
    to: resolveAnchor(toNode, connector.to.anchor),
    marker_end: connector.marker_end || "none",
  };
}

function clipFunctionLine(line) {
  const [minX, maxX] = line.domain || [-5, 5];
  assertFinite(line.slope, `${line.id}.slope`);
  assertFinite(line.intercept, `${line.id}.intercept`);
  if (!(minX < maxX)) throw new Error(`${line.id}.domain must be ascending`);
  return {
    id: line.id,
    label: line.label || line.id,
    points: [
      { x: minX, y: line.slope * minX + line.intercept },
      { x: maxX, y: line.slope * maxX + line.intercept },
    ],
    equation: { slope: line.slope, intercept: line.intercept },
  };
}

function compileMotionCanvasAdapter(scene) {
  const lines = scene.function_lines.map(line => `functionLine(${JSON.stringify(line.id)}, ${line.equation.slope}, ${line.equation.intercept}, ${JSON.stringify(line.points)})`);
  const connectors = scene.connectors.map(connector => `connector(${JSON.stringify(connector.id)}, ${JSON.stringify(connector.from)}, ${JSON.stringify(connector.to)})`);
  return [
    "// Generated by the trusted hybrid adapter. This text is an audit artifact, never eval'd.",
    "export function buildScene(adapter) {",
    "  const {node, connector, functionLine, move} = adapter;",
    ...scene.nodes.map(item => `  node(${JSON.stringify(item.id)}, ${JSON.stringify(item)});`),
    ...connectors.map(line => `  ${line};`),
    ...lines.map(line => `  ${line};`),
    ...scene.timeline.map(action => `  move(${JSON.stringify(action.target_id)}, ${JSON.stringify(action.to)}, ${action.duration_ms});`),
    "}",
  ].join("\n");
}

function lineIntersection(first, second) {
  const denominator = first.equation.slope - second.equation.slope;
  if (Math.abs(denominator) < 1e-9) return null;
  const x = (second.equation.intercept - first.equation.intercept) / denominator;
  const y = first.equation.slope * x + first.equation.intercept;
  return {x, y};
}

export function compileHybridScene(input) {
  if (!input || input.schema_version !== "hybrid-visual-scene/0.1") throw new Error("unsupported hybrid schema");
  if (!Array.isArray(input.nodes) || input.nodes.length < 1) throw new Error("nodes are required");
  const nodes = new Map(input.nodes.map(node => { validateNode(node); return [node.id, {...node}]; }));
  if (nodes.size !== input.nodes.length) throw new Error("duplicate node id");
  const connectors = (input.connectors || []).map(connector => resolveConnector(connector, nodes));
  const function_lines = (input.function_lines || []).map(clipFunctionLine);
  const timeline = (input.timeline || []).map(action => {
    if (!nodes.has(action.target_id)) throw new Error(`timeline references unknown node: ${action.target_id}`);
    if (!Number.isInteger(action.duration_ms) || action.duration_ms < 0 || action.duration_ms > 20000) throw new Error("timeline duration is invalid");
    for (const key of ["x", "y"]) if (action.to?.[key] !== undefined) assertFinite(action.to[key], `timeline.${action.target_id}.${key}`);
    return {target_id: action.target_id, to: {...action.to}, duration_ms: action.duration_ms};
  });
  const derived = {};
  if (function_lines.length >= 2) derived.first_intersection = lineIntersection(function_lines[0], function_lines[1]);
  const compiled = {schema_version: input.schema_version, nodes: [...nodes.values()], connectors, function_lines, timeline, derived, _connector_specs: input.connectors || []};
  return {...compiled, motion_canvas_adapter_source: compileMotionCanvasAdapter(compiled)};
}

export function evaluateHybridFrame(compiled, progress = 0) {
  const fraction = Math.min(1, Math.max(0, progress));
  const nodes = new Map(compiled.nodes.map(node => [node.id, {...node}]));
  for (const action of compiled.timeline) {
    const node = nodes.get(action.target_id);
    for (const [key, target] of Object.entries(action.to)) node[key] = node[key] + (target - node[key]) * fraction;
  }
  return {...compiled, nodes: [...nodes.values()], connectors: compiled._connector_specs.map(item => resolveConnector(item, nodes))};
}
